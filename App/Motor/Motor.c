/*********************************************************************************************************
* 函数名称：SetMotorStrength
* 函数功能：设置Motor模式
* 输入参数：mode
* 输出参数：void
* 返 回 值：void
* 创建日期：2026年05月11日
* 注    意：每10ms调用一次
*********************************************************************************************************/
void SetMotorMode(u8 mode)
{
  static u8 state;
  static u16 cnt;
  
  switch (mode)
  {
  case STRONG:          //强震模式
    SetPWM(100);
    printf("strong\n");
    break;
  case PULSE:           //脉冲模式，运行4s，停止1s
    cnt++;
    if(state==START){   //启动状态
      StartMotor();
      if(cnt==400){     
        state=STOP;
      }
    }else{              //停止状态
      StopMotor();
      if(cnt==500){
        cnt=0;
        state=START;
      }
    }
    printf("pulse\n");
    break;
  case SLEEP:           //睡眠模式
    AlterPWMDutyCycle();  
    printf("sleep\n");
    break;
    
  default:
    break;
  }
}