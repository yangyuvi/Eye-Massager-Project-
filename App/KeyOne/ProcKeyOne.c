void OnKey2Event(KeyEvent event)
{ 
  //切换模式语音播报本地Flash
  switch (event)
  {
  case KEY_EVENT_UP:
    if(++mode == MODE_MAX){
      mode = 0;
    }
    printf("%d\n",mode);
    break;
  case KEY_EVENT_DOUBLE:
    printf("double\n");
    break;
  case KEY_EVENT_LONG:
    printf("LONG\n");
    break;
  default:
    break;
  }
  
}

